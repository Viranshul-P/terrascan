"""Confusion analysis (step 3.1): which class pairs does the best model mix up on the TEST split?

Uses the test split only to look at mistakes. Nothing here changes a model or a setting.

Run from the repo root:
    python -m src.confusion --config configs/confusion.yaml
"""

import argparse
import json
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # save PNGs without opening a window
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import torch  # noqa: E402
import yaml  # noqa: E402

from src.data import CLASSES, build_dataloaders, read_image  # noqa: E402
from src.evaluate import load_run, predict  # noqa: E402
from src.metrics import confusion_matrix  # noqa: E402


def pick_best_model(candidates, seeds):
    """Return the candidate with the highest mean VAL accuracy, plus that mean.

    Reads best_val_acc from models/<run>/seed<N>/metrics.json. Test numbers are never used here.
    """
    best, best_mean = None, -1.0
    for entry in candidates:
        accs = []
        for seed in seeds:
            path = Path(entry["run_dir"]) / f"seed{seed}" / "metrics.json"
            accs.append(json.loads(path.read_text(encoding="utf-8"))["best_val_acc"])
        mean = statistics.mean(accs)
        if mean > best_mean:
            best, best_mean = entry, mean
    return best, best_mean


def top_confused_pairs(matrix, k):
    """The k class pairs with the most mistakes, counting both directions together.

    matrix[i][j] = images of true class i predicted as j.
    Returns a list of (a, b, a_as_b, b_as_a), biggest total first. Ties keep class order.
    """
    n = len(matrix)
    pairs = []
    for a in range(n):
        for b in range(a + 1, n):
            a_as_b, b_as_a = int(matrix[a][b]), int(matrix[b][a])
            if a_as_b + b_as_a > 0:
                pairs.append((a, b, a_as_b, b_as_a))
    pairs.sort(key=lambda p: p[2] + p[3], reverse=True)  # sort is stable, so ties stay in order
    return pairs[:k]


def save_mistake_grid(pairs, test_df, raw_dir, preds, labels, max_per_pair, path):
    """One row per pair: wrongly classified test images (original 64x64), titled true -> pred."""
    fig, axes = plt.subplots(
        len(pairs), max_per_pair, figsize=(1.9 * max_per_pair, 2.1 * len(pairs)), squeeze=False
    )
    for row, (a, b, _, _) in enumerate(pairs):
        wrong = ((labels == a) & (preds == b)) | ((labels == b) & (preds == a))
        idx = wrong.nonzero().flatten().tolist()
        for col in range(max_per_pair):
            ax = axes[row][col]
            ax.axis("off")
            if col >= len(idx):
                continue
            i = idx[col]
            image = read_image(Path(raw_dir) / test_df.iloc[i]["path"])
            ax.imshow(image.permute(1, 2, 0).numpy())
            ax.set_title(
                f"{CLASSES[labels[i]]}\n-> {CLASSES[preds[i]]}", fontsize=7
            )
        axes[row][0].text(
            -0.15, 0.5, f"{CLASSES[a]} / {CLASSES[b]}\n({len(idx)} mistakes)",
            transform=axes[row][0].transAxes, ha="right", va="center", fontsize=8,
        )
    fig.suptitle("Most-confused class pairs (test split): true -> predicted", fontsize=10)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120, bbox_inches="tight")
    plt.close(fig)


def write_table(pairs, model_name, seed, val_mean, path):
    lines = [
        f"# Most-confused class pairs: {model_name}, seed {seed}, TEST split",
        "",
        f"Model picked by highest mean VAL accuracy ({val_mean:.4f}, from "
        f"models/{model_name}/seed*/metrics.json). Generated by `python -m src.confusion`.",
        "Both directions are counted together; the last two columns show each direction.",
        "",
        "| Rank | Class A | Class B | Total mistakes | A predicted as B | B predicted as A |",
        "|---|---|---|---|---|---|",
    ]
    for rank, (a, b, a_as_b, b_as_a) in enumerate(pairs, start=1):
        lines.append(
            f"| {rank} | {CLASSES[a]} | {CLASSES[b]} | {a_as_b + b_as_a} | {a_as_b} | {b_as_a} |"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = yaml.safe_load(open(args.config, encoding="utf-8"))

    best, val_mean = pick_best_model(cfg["candidates"], cfg["val_seeds"])
    print(f"Best model by mean val accuracy: {best['name']} ({val_mean:.4f})")

    run_dir = Path(best["run_dir"]) / f"seed{cfg['seed']}"
    model, run_cfg = load_run(run_dir)
    data_cfg = run_cfg["data"]
    _, _, test_loader = build_dataloaders(
        data_cfg,
        run_cfg.get("image_size", 64),
        run_cfg.get("norm_stats"),
        run_cfg.get("target_stats"),
    )
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    preds, labels = predict(model, test_loader, device)
    matrix = confusion_matrix(preds, labels, len(CLASSES))

    # Safety check: must match the matrix step 2.5 saved, so predictions line up with that run.
    saved = json.loads(
        (Path(cfg["results_dir"]) / f"{best['name']}.json").read_text(encoding="utf-8")
    )["seeds"][str(cfg["seed"])]["confusion_matrix"]
    if matrix.tolist() != saved:
        raise SystemExit("Confusion matrix differs from the one saved in step 2.5. Stopping.")
    print("Confusion matrix matches the saved step 2.5 matrix.")

    pairs = top_confused_pairs(matrix.tolist(), cfg["top_k"])
    for a, b, a_as_b, b_as_a in pairs:
        print(f"{CLASSES[a]} / {CLASSES[b]}: {a_as_b + b_as_a} ({a_as_b} + {b_as_a})")

    write_table(pairs, best["name"], cfg["seed"], val_mean, Path(cfg["table_path"]))
    test_df = pd.read_csv(Path(data_cfg["splits_dir"]) / "test.csv")  # loader isn't shuffled
    save_mistake_grid(
        pairs, test_df, data_cfg["raw_dir"], preds, labels,
        cfg["max_images_per_pair"], Path(cfg["figure_path"]),
    )
    print(f"Saved {cfg['table_path']} and {cfg['figure_path']}")


if __name__ == "__main__":
    main()
