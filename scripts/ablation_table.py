"""Write results/small_cnn_ablation.md from the experiment list and each run's metrics.json.

The words (change, reason, kept?) come from configs/small_cnn_exp/ablation.yaml.
Every number is read from models/<run>/metrics.json; nothing is typed by hand.

Run from the repo root:
    python scripts/ablation_table.py
"""

import json
from pathlib import Path

import yaml

ROWS_PATH = Path("configs/small_cnn_exp/ablation.yaml")
OUT_PATH = Path("results/small_cnn_ablation.md")


def main():
    rows = yaml.safe_load(ROWS_PATH.read_text(encoding="utf-8"))
    lines = [
        "# SmallCNN ablation (step 2.2c)",
        "",
        "One change at a time, one seed, judged on the **val** split only (test is not used).",
        f"Generated by `scripts/ablation_table.py` from `{ROWS_PATH.as_posix()}` and each run's",
        "`metrics.json` (numbers at the epoch with the lowest val loss).",
        "",
        "| # | Change | Why try it | Val acc | Val macro-F1 | Params | Best epoch / run | Kept? "
        "| Source |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for i, row in enumerate(rows):
        metrics_path = Path("models") / row["run"] / "metrics.json"
        m = json.loads(metrics_path.read_text(encoding="utf-8"))
        lines.append(
            f"| {i} | {row['change']} | {row['reason']} | {m['best_val_acc']:.4f} "
            f"| {m['best_val_f1']:.4f} | {m['params']:,} | {m['best_epoch']} / {m['epochs_run']} "
            f"| {row['kept']} | `{metrics_path.as_posix()}` |"
        )
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Saved {OUT_PATH} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
