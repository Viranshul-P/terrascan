"""Write results/comparison.md from the results/<model>.json files made by src/evaluate.py.

Every number is read from those JSON files; nothing is typed by hand.

Run from the repo root:
    python scripts/comparison_table.py
"""

import json
import statistics
from pathlib import Path

import yaml

EVAL_CONFIG = Path("configs/evaluate.yaml")
OUT_PATH = Path("results/comparison.md")


def mean_std(values, digits=4):
    """'mean ± std' over seeds (sample std), or just the value when there is one seed."""
    if len(values) == 1:
        return f"{values[0]:.{digits}f} (1 seed)"
    return f"{statistics.mean(values):.{digits}f} ± {statistics.stdev(values):.{digits}f}"


def accuracy_range(seeds):
    """(low, high) = mean - std, mean + std of test accuracy over seeds."""
    accs = [s["accuracy"] for s in seeds.values()]
    if len(accs) == 1:
        return accs[0], accs[0]
    m, sd = statistics.mean(accs), statistics.stdev(accs)
    return m - sd, m + sd


def main():
    cfg = yaml.safe_load(EVAL_CONFIG.read_text(encoding="utf-8"))
    results = {}
    for entry in cfg["models"]:
        path = Path(cfg["results_dir"]) / f"{entry['name']}.json"
        results[entry["name"]] = json.loads(path.read_text(encoding="utf-8"))

    lines = [
        "# Model comparison on the EuroSAT test split (step 2.5)",
        "",
        "Generated by `scripts/comparison_table.py` from `results/<model>.json`",
        "(made by `src/evaluate.py`).",
        "Test split = 15% of EuroSAT, used only here. Values are mean ± std over seeds 42, 43, 44",
        "(sample std), except SmallCNN v1 (one seed).",
        "",
        "| Model | Seeds | Input | Params | Test accuracy | Test macro-F1 | CPU ms/image |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, res in results.items():
        seeds = res["seeds"]
        first = next(iter(seeds.values()))
        lines.append(
            f"| {name} | {', '.join(seeds)} | {first['image_size']}×{first['image_size']} "
            f"| {first['params']:,} "
            f"| {mean_std([s['accuracy'] for s in seeds.values()])} "
            f"| {mean_std([s['macro_f1'] for s in seeds.values()])} "
            f"| {mean_std([s['cpu_ms_per_image'] for s in seeds.values()], digits=2)} |"
        )
    any_res = next(iter(results.values()))
    lines += [
        "",
        f"CPU ms/image: model only (no JPEG reading or resizing), batch size 1, float32, "
        f"{any_res['cpu_threads']} CPU thread, median of {any_res['timed_runs']} runs after "
        f"{any_res['warmup_runs']} warm-up runs, on the laptop used for training.",
        "Input: pretrained models see the 64×64 images scaled up to 128×128 (step 2.3 rule).",
        "",
        "## Accuracy ranges that overlap",
        "",
        "Range = mean ± std of test accuracy. If two ranges overlap, call the models",
        "about the same. SmallCNN v1 has one seed, so its range is a single point.",
        "With only 3 seeds, std is rough.",
        "",
    ]
    names = list(results)
    for i, a in enumerate(names):
        for b in names[i + 1 :]:
            lo_a, hi_a = accuracy_range(results[a]["seeds"])
            lo_b, hi_b = accuracy_range(results[b]["seeds"])
            overlap = lo_a <= hi_b and lo_b <= hi_a
            lines.append(f"- {a} vs {b}: {'overlap (about the same)' if overlap else 'no overlap'}")
    three_seed = {n: r for n, r in results.items() if len(r["seeds"]) == 3}
    means = {
        n: statistics.mean(s["accuracy"] for s in r["seeds"].values())
        for n, r in three_seed.items()
    }
    best, worst = max(means, key=means.get), min(means, key=means.get)
    n_test = next(iter(results[best]["seeds"].values()))["n_test_images"]
    gap = means[best] - means[worst]
    lines += [
        "",
        f"Gap between the best and worst 3-seed model means: {gap * 100:.2f} percentage points "
        f"({best} vs {worst}), about {gap * n_test:.0f} of {n_test} test images.",
    ]

    classes = list(any_res["seeds"][next(iter(any_res["seeds"]))]["per_class_f1"])
    lines += [
        "",
        "## Per-class F1 (mean over seeds)",
        "",
        "| Class | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for c in classes:
        row = [
            statistics.mean(s["per_class_f1"][c] for s in results[n]["seeds"].values())
            for n in names
        ]
        lines.append(f"| {c} | " + " | ".join(f"{v:.4f}" for v in row) + " |")

    lines += [
        "",
        "## SmallCNN v1 → v2 (step 2.2c experiments)",
        "",
    ]
    v1, v2 = results["small_cnn_v1"]["seeds"], results["small_cnn_v2"]["seeds"]
    lines.append(f"- v1 test accuracy: {mean_std([s['accuracy'] for s in v1.values()])}")
    lines.append(f"- v2 test accuracy: {mean_std([s['accuracy'] for s in v2.values()])}")
    lines.append("- Confusion matrices (seed 42): `reports/figures/confusion_<model>.png`")
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Saved {OUT_PATH}")


if __name__ == "__main__":
    main()
